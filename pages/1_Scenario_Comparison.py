# --------------------------------------------------
# SCENARIO DEFINITIONS
# --------------------------------------------------

SCENARIOS = [
    ("Movie Night", 20, 20, 30),
    ("Living Room", 50, 40, 40),
    ("Gaming", 80, 80, 60),
    ("Sports", 90, 90, 70),
    ("Streaming", 60, 70, 40)
]


# --------------------------------------------------
# RUN THE MODEL FOR EACH SCENARIO
# --------------------------------------------------

rows = []

for name, ambient, content, volume in SCENARIOS:

    brightness = recommended_backlight(
        ambient,
        content,
        False
    )

    conventional = wall_power(
        brightness_pct=100,
        volume_pct=volume,
        wifi_on=True
    )

    optimized = wall_power(
        brightness_pct=brightness,
        volume_pct=volume,
        wifi_on=True
    )

    conventional_power = conventional["WallPower"]
    optimized_power = optimized["WallPower"]

    power_saved = conventional_power - optimized_power

    if conventional_power > 0:
        saving_pct = (
            power_saved / conventional_power
        ) * 100
    else:
        saving_pct = 0.0

    rows.append({
        "Scenario": name,
        "Ambient Light (%)": ambient,
        "Content Brightness (%)": content,
        "Volume (%)": volume,
        "Recommended Brightness (%)": brightness,
        "Conventional Power (W)": conventional_power,
        "Optimized Power (W)": optimized_power,
        "Power Saved (W)": power_saved,
        "Savings (%)": saving_pct
    })


df = pd.DataFrame(rows)


# --------------------------------------------------
# SUMMARY METRICS
# --------------------------------------------------

avg_saving = df["Savings (%)"].mean()
avg_power_saved = df["Power Saved (W)"].mean()

best_row = df.loc[df["Savings (%)"].idxmax()]
lowest_row = df.loc[df["Savings (%)"].idxmin()]

