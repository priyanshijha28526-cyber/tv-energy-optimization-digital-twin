def style_chart(fig, height=380):
    """Apply a consistent visual style to Plotly charts."""

    fig.update_layout(
        height=height,
        paper_bgcolor="white",
        plot_bgcolor="white",
        font=dict(
            family="Arial",
            color="#172033",
            size=12
        ),
        margin=dict(
            l=35,
            r=25,
            t=75,
            b=45
        ),
        title=dict(
            x=0.03,
            xanchor="left"
        ),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=1.02,
            xanchor="right",
            x=1
        )
    )

    fig.update_xaxes(
        showgrid=False,
        linecolor="#E2E8F0"
    )

    fig.update_yaxes(
        gridcolor="#E8EDF4",
        zerolinecolor="#94A3B8"
    )

    return fig


